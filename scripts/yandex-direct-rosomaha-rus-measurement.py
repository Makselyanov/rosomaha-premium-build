def _attempt_measurement_restore(
    api: Any, baseline_campaign: Mapping[str, Any], desired: Mapping[str, Any]
) -> dict[str, Any]:
    receipt: dict[str, Any] = {"status": "not_safe", "mutation_requests": 0}
    mutations_before = int(getattr(api, "mutation_requests", 0))
    try:
        baseline = copy.deepcopy(dict(baseline_campaign))
        validate_canonical_campaign(baseline, require_draft=True)
        original = measurement(baseline)
        current = read_campaign(api, CANONICAL_API_VERSION)
        validate_canonical_campaign(current, require_draft=True)
        current_measurement = measurement(current)
        if (
            current_measurement == original
            and _campaign_without_measurement(current)
            == _campaign_without_measurement(baseline)
        ):
            receipt.update(status="baseline_intact", reason="mutation was not committed")
            return receipt
        if (
            current_measurement != dict(desired)
            or _campaign_without_measurement(current)
            != _campaign_without_measurement(baseline)
        ):
            receipt.update(
                status="manual_inspection_required",
                reason="current campaign is neither exact baseline nor exact candidate",
                current_measurement_sha256=sha256_json(current_measurement),
                current_campaign_sha256=sha256_json(current),
            )
            return receipt
        payload = restore_update(original)
        try:
            result = api.call(
                CANONICAL_API_VERSION,
                "campaigns",
                "update",
                payload,
                use_client_login=True,
                mutation_kind="restore_measurement",
            )
            _assert_action_results(result, "UpdateResults", [TARGET_CAMPAIGN_ID])
            restored = read_campaign(api, CANONICAL_API_VERSION)
            validate_canonical_campaign(restored, require_draft=True)
            if (
                measurement(restored) != original
                or _campaign_without_measurement(restored)
                != _campaign_without_measurement(baseline)
            ):
                raise OperatorError("Restore readback не совпал с полным точным preimage")
            receipt.update(status="restored", restored_measurement_sha256=sha256_json(original))
        except Exception as restore_exc:
            receipt["restore_error"] = _safe_text(restore_exc)
            if isinstance(restore_exc, OperatorError) and restore_exc.partial:
                receipt.update(restore_exc.partial)
            try:
                restored = read_campaign(api, CANONICAL_API_VERSION)
                validate_canonical_campaign(restored, require_draft=True)
                if (
                    measurement(restored) == original
                    and _campaign_without_measurement(restored)
                    == _campaign_without_measurement(baseline)
                ):
                    receipt["status"] = "restored_readback_after_ambiguous_response"
                else:
                    receipt["status"] = "manual_inspection_required"
            except Exception as read_exc:
                receipt.update(
                    status="manual_inspection_required",
                    restore_readback_error=_safe_text(read_exc),
                )
    except Exception as exc:
        receipt.update(status="manual_inspection_required", error=_safe_text(exc))
        if isinstance(exc, OperatorError) and exc.partial:
            receipt.update(exc.partial)
    receipt["mutation_requests"] = int(getattr(api, "mutation_requests", 0)) - mutations_before
    return receipt


